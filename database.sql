create table if not exists public.fitness_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  age integer check (age between 16 and 100),
  sex text default 'prefer_not_to_say',
  height_cm numeric(6,2),
  current_weight_kg numeric(6,2),
  target_weight_kg numeric(6,2),
  goal text default 'general_fitness',
  activity_level text default 'moderate',
  experience text default 'beginner',
  equipment text[] default array['gym'],
  training_days integer default 4 check (training_days between 2 and 7),
  diet_type text default 'both',
  allergies text,
  limitations text,
  preferred_session_minutes integer default 60,
  updated_at timestamptz default now()
);

create table if not exists public.workout_plans (
