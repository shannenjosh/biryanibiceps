create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  goal text default '',
  plan text default 'Monthly',
  created_at timestamptz not null default now()
);
create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null,
  trainer text default 'B&B Trainer',
  starts_at text not null,
  capacity integer not null default 20,
  created_at timestamptz not null default now()
);
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  class_id bigint not null references public.classes(id) on delete cascade,
  status text not null default 'Booked',
  created_at timestamptz not null default now(),
  unique(user_id,class_id)
);
create table if not exists public.workouts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise text not null,
  sets integer not null,
  reps integer not null,
  weight_kg numeric(6,2) default 0,
  workout_date date not null default current_date,
  created_at timestamptz not null default now()
);
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount numeric(10,2) not null,
  description text default 'Membership',
  status text not null default 'Pending',
  payment_date date not null default current_date,
  created_at timestamptz not null default now()
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text default '',
  is_read boolean default false,
  created_at timestamptz not null default now()
);
create table if not exists public.progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  weight_kg numeric(6,2) not null,
  height_cm numeric(6,2),
  recorded_on date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.classes enable row level security;
alter table public.bookings enable row level security;
alter table public.workouts enable row level security;
alter table public.payments enable row level security;
alter table public.notifications enable row level security;
alter table public.progress enable row level security;

create policy "Users can read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "Users can insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "Authenticated users can view classes" on public.classes for select to authenticated using (true);
create policy "Users manage own bookings" on public.bookings for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own workouts" on public.workouts for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own payments" on public.payments for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own notifications" on public.notifications for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own progress" on public.progress for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

